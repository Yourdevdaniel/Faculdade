    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int horas = Integer.parseInt(JOptionPane.showInputDialog("Digite a quantidade de horas:"));

        double valor = calcularValorEstacionamento(horas);

        if (valor == -1) {
           taSaida.setText(
                    "Quantidade de horas inválida.");
        } else {
           taSaida.setText(
                    "Valor a pagar: R$ " + valor);
    }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int idade = Integer.parseInt(JOptionPane.showInputDialog("Digite a idade:"));

        String autorizacao = JOptionPane.showInputDialog("Possui autorização especial? (sim ou não)");

        boolean acesso = verificarAcessoAreaRestrita(idade, autorizacao);

        if (acesso) {
           taSaida.setText( "Acesso permitido.");
        } else {
           taSaida.setText( "Acesso negado.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

