    public boolean verificarAcessoAreaRestrita(int idade, String autorizacao) {

        if (idade >= 18) return true;        

        if (autorizacao.equalsIgnoreCase("sim"))   return true;
        
        return false;
    }    

    public void exibirMensagemRecepcao(String nome) {

        taSaida.append("\nBem-vindo ao espaço de visitação, " + nome + "!\n");
    }
    
// MÉTODO 1 PEDIDO
    public double calcularValorEstacionamento(int horas) {
        if (horas <= 0) return -1;

        if (horas <= 2)  return 10.0;
        
        return 10.0 + (horas - 2) * 4.0;
    }

    // MÉTODO 2 PEDIDO
    public void verificarDireitoSorteio(int quantidadeVisitas) {
        if (quantidadeVisitas >= 5) {
            taSaida.setText("Você tem direito a participar do sorteio mensal.");
        } else {
            taSaida.setText("Você não tem direito a participar do sorteio mensal.");
        }
    }    
    
